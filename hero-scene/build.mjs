// Bundles main.js into one HTML page and writes it where the app imports it. three.js itself loads from a pinned
// CDN copy through the page's import map: inlined, its 550 KB string ran Metro out of memory.
// Run from hero-scene/: `npm run build` (needs bun). Also writes dist/index.html to open on its own.
import { mkdirSync } from 'node:fs';

const THREE_VERSION = JSON.parse(await Bun.file('./node_modules/three/package.json').text()).version;
const r = await Bun.build({ entrypoints: ['./main.js'], minify: true, target: 'browser', format: 'esm', external: ['three', 'three/addons/*'] });
if (!r.success) { console.error(r.logs); process.exit(1); }
const js = (await r.outputs[0].text()).replaceAll('</script', '<\\/script');
const html = (await Bun.file('./index.html').text()).replaceAll('THREE_VERSION', THREE_VERSION).replace('/*SCENE*/', () => js);

mkdirSync('./dist', { recursive: true });
await Bun.write('./dist/index.html', html);
await Bun.write(
  '../src/hero/sceneHtml.ts',
  `// Generated by hero-scene/build.mjs from hero-scene/main.js. Do not edit; run \`npm run build\` in hero-scene/.\n` +
    `export const SCENE_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`scene: ${(html.length / 1024).toFixed(0)} KB`);
