// Bundles scene.js into one HTML page and writes it where the app imports it (src/mood/poolHtml.ts).
// Run from mood-scene/: `bun build.mjs`. Also writes dist/index.html to open on its own (drive it with the mouse).
import { mkdirSync } from 'node:fs';

const r = await Bun.build({ entrypoints: ['./scene.js'], minify: true, target: 'browser', format: 'iife' });
if (!r.success) { console.error(r.logs); process.exit(1); }
const js = (await r.outputs[0].text()).replaceAll('</script', '<\/script');
const html = (await Bun.file('./index.html').text()).replace('/*SCENE*/', () => js);

mkdirSync('./dist', { recursive: true });
await Bun.write('./dist/index.html', html);
await Bun.write(
  '../src/mood/poolHtml.ts',
  `// Generated by mood-scene/build.mjs from mood-scene/scene.js. Do not edit; run \`bun build.mjs\` in mood-scene/.\n` +
    `export const POOL_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`pool: ${(html.length / 1024).toFixed(0)} KB`);
