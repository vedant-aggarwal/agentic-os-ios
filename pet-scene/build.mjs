// Bundles the pet scene (main.js, shader.js, sim.js, rig.js) into one self-contained HTML page and writes it where
// the app imports it. No three.js, no network: the creature is one fragment shader.
// Run from pet-scene/: `bun build.mjs`. Also writes dist/index.html to open on its own (?size=200 etc.).
import { mkdirSync } from 'node:fs';

const r = await Bun.build({ entrypoints: ['./main.js'], minify: true, target: 'browser', format: 'iife' });
if (!r.success) { console.error(r.logs); process.exit(1); }
const js = (await r.outputs[0].text()).replaceAll('</script', '<\/script');
const html = (await Bun.file('./index.html').text()).replace('/*SCENE*/', () => js);

mkdirSync('./dist', { recursive: true });
await Bun.write('./dist/index.html', html);
await Bun.write(
  '../src/pet/sceneHtml.ts',
  `// Generated by pet-scene/build.mjs from pet-scene/*.js. Do not edit; run \`bun build.mjs\` in pet-scene/.\n` +
    `// The app swaps /*CFG*/null for the instance's settings before loading it.\n` +
    `export const PET_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`pet scene: ${(html.length / 1024).toFixed(0)} KB`);
